[[nodiscard]] const uint8_t* GlyphFor(char value) noexcept {
  auto code = static_cast<uint8_t>(value);
  if (code < kFirstGlyph || code > kLastGlyph) {
    code = static_cast<uint8_t>('?');
  }
  return kFont[code - kFirstGlyph];
}

